def build_controls_reference() -> str:
    lines = ["=== ISO 27001:2022 CONTROLS ===\n"]
    for domain_id, domain in ISO_27001_CONTROLS.items():
        lines.append(f"\n{domain_id} — {domain['name']}")
        for ctrl_id, ctrl_name in domain["controls"].items():
            lines.append(f"  {ctrl_id}: {ctrl_name}")

    lines.append("\n\n=== SOC 2 TRUST SERVICE CRITERIA ===\n")
    for category_id, category in SOC2_CONTROLS.items():
        lines.append(f"\n{category_id} — {category['name']}")
        key = "controls" if "controls" in category else "criteria"
        for ctrl_id, ctrl_name in category[key].items():
            lines.append(f"  {ctrl_id}: {ctrl_name}")

    return "\n".join(lines)
